import re


class Moderator:
    """Словарная модерация этики: маты, оскорбления, токсичность.

    Первый уровень защиты: словарь расширяемый. Намеренно без LLM-оценки,
    чтобы периметр ПДн не расширялся — проверка выполняется локально.
    """

    _BANNED_RE = re.compile(
        r"(?i)"
        r"(ху[йяеёюи]\w*"
        r"|пизд\w*"
        r"|бля[дт]\w*"
        r"|заеб\w*"
        r"|выеб\w*"
        r"|ебал\w*"
        r"|ебан\w*"
        r"|ебет"
        r"|ебёт"
        r"|сука"
        r"|суки"
        r"|сукой"
        r"|сучк\w*"
        r"|шлюх\w*"
        r"|пид[оа]р\w*"
        r"|пидр\w*"
        r"|манда\w*"
        r"|мудил\w*"
        r"|гандон\w*"
        r"|долбо[её]б\w*"
        r"|идиот\w*"
        r"|дебил\w*"
        r"|тупиц\w*"
        r"|урод\w*"
        r"|черножоп\w*"
        r"|нигг\w*"
        r")"
    )

    def is_clean(self, text: str) -> bool:
        return self._BANNED_RE.search(text) is None
