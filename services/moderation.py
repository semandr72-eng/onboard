import re


class Moderator:
    """Словарная модерация этики: маты, оскорбления, токсичность.

    Первый уровень защиты: словарь расширяемый. Намеренно без LLM-оценки,
    чтобы периметр ПДн не расширялся — проверка выполняется локально.
    """

    # \b у всех корней: без него «команда» ловилось корнем «манда»,
    # «небанальный» — «ебан», «ступица» — «тупиц».
    _BANNED_RE = re.compile(
        r"(?i)"
        r"(\bху[йяеёюи]\w*"
        r"|\bпизд\w*"
        r"|\bбля[дт]\w*"
        r"|\bзаеб\w*"
        r"|\bвыеб\w*"
        r"|\bебал\w*"
        r"|\bебан\w*"
        r"|\bебет"
        r"|\bебёт"
        r"|\bсука"
        r"|\bсуки"
        r"|\bсукой"
        r"|\bсучк\w*"
        r"|\bшлюх\w*"
        r"|\bпид[оа]р\w*"
        r"|\bманда\w*"
        r"|\bмудил\w*"
        r"|\bгандон\w*"
        r"|\bдолбо[её]б\w*"
        r"|\bидиот\w*"
        r"|\bдебил\w*"
        r"|\bтупиц\w*"
        r"|\bурод\w*"
        r"|\bчерножоп\w*"
        r"|\bнигг\w*"
        r")"
    )

    def is_clean(self, text: str) -> bool:
        return self._BANNED_RE.search(text) is None
